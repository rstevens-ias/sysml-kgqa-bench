def compute_excluded_ids(id_index):
    """Map every element id to whether it lies below one of EXCLUDED_ROOT_IDS."""
    memo = {}

    def is_excluded(node_id, seen=None):
        if node_id in memo:
            return memo[node_id]
        if node_id in EXCLUDED_ROOT_IDS:
            memo[node_id] = True
            return True
        node = id_index.get(node_id)
        if not node or not node.get("parent_id"):
            memo[node_id] = False
            return False
        seen = seen or set()
        if node_id in seen:
            memo[node_id] = False
            return False
        seen.add(node_id)
        result = is_excluded(node["parent_id"], seen)
        memo[node_id] = result
        return result

    for nid in id_index:
        is_excluded(nid)
    return memo


